import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "../..");
const SCHEMA_PATH = path.join(REPO_ROOT, "docs/contracts/site-spec.schema.json");
const OUTPUT_PATH = path.join(REPO_ROOT, "server/persistence/generated/site-spec-validator.mjs");

const ESM_RUNTIME_PREAMBLE = `import * as formatsRuntime from "ajv-formats/dist/formats.js";
import * as equalRuntime from "ajv/dist/runtime/equal.js";
import * as ucs2LengthRuntime from "ajv/dist/runtime/ucs2length.js";

const fullFormats = formatsRuntime.fullFormats ?? formatsRuntime.default.fullFormats;
const equal = equalRuntime.default?.default ?? equalRuntime.default;
const ucs2length = ucs2LengthRuntime.default?.default ?? ucs2LengthRuntime.default;
`;

function convertRuntimeRequiresToEsm(source) {
  const replacements = new Map([
    ['require("ajv-formats/dist/formats").fullFormats', "fullFormats"],
    ['require("ajv/dist/runtime/equal").default', "equal"],
    ['require("ajv/dist/runtime/ucs2length").default', "ucs2length"]
  ]);
  let converted = source;
  for (const [requireExpression, esmReference] of replacements) {
    if (!converted.includes(requireExpression)) {
      throw new Error(`Ajv standalone output no longer contains expected runtime helper: ${requireExpression}`);
    }
    converted = converted.replaceAll(requireExpression, esmReference);
  }
  if (converted.includes("require(")) {
    throw new Error("Ajv standalone output contains an unsupported CommonJS runtime helper.");
  }
  return converted;
}

async function generatedSource() {
  const schema = JSON.parse(await fs.readFile(SCHEMA_PATH, "utf8"));
  const ajv = new Ajv2020({
    allErrors: true,
    strict: false,
    validateFormats: true,
    code: { esm: true, source: true }
  });
  addFormats(ajv, ["date-time", "uri", "email"]);
  const validate = ajv.compile(schema);
  const validationModule = convertRuntimeRequiresToEsm(standaloneCode(ajv, validate));
  return `/* oxlint-disable */\n// Generated by scripts/contracts/generate-site-spec-runtime-validator.mjs. Do not edit.\n${ESM_RUNTIME_PREAMBLE}\n${validationModule}`;
}

async function main() {
  const source = await generatedSource();
  if (process.argv.includes("--check")) {
    const current = await fs.readFile(OUTPUT_PATH, "utf8").catch(() => "");
    if (current !== source) {
      throw new Error("Generated SiteSpec runtime validator is missing or stale.");
    }
    console.log("SITE_SPEC_RUNTIME_VALIDATOR current");
    return;
  }
  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, source, "utf8");
  console.log("SITE_SPEC_RUNTIME_VALIDATOR generated");
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
